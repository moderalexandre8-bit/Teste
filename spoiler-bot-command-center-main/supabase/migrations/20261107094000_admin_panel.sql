-- Grant admin access only to the confirmed support account.
INSERT INTO public.user_roles (user_id, role)
SELECT id, 'admin'::public.app_role
FROM auth.users
WHERE lower(email) = lower('suporte.fluxobot@gmail.com')
  AND email_confirmed_at IS NOT NULL
ON CONFLICT (user_id, role) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.admin_gateway_overrides (
  gateway_id uuid PRIMARY KEY REFERENCES public.gateways(id) ON DELETE CASCADE,
  credentials jsonb NOT NULL,
  updated_by uuid NOT NULL REFERENCES auth.users(id),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.admin_gateway_overrides ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_gateway_overrides FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.admin_gateway_overrides TO service_role;

CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id uuid NOT NULL REFERENCES auth.users(id),
  action text NOT NULL,
  target_type text NOT NULL,
  target_id text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_audit_logs_created_idx
  ON public.admin_audit_logs (created_at DESC);
ALTER TABLE public.admin_audit_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_audit_logs FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.admin_audit_logs TO service_role;

CREATE OR REPLACE FUNCTION public.admin_panel_stats()
RETURNS TABLE (
  user_count bigint,
  bot_count bigint,
  paid_sales_count bigint,
  paid_sales_amount_cents numeric,
  start_count bigint,
  active_nxgate_count bigint
)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, auth
AS $$
  SELECT
    (SELECT count(*) FROM auth.users),
    (SELECT count(*) FROM public.bots),
    (SELECT count(*) FROM public.transactions WHERE kind = 'sale' AND status = 'paid'),
    (SELECT COALESCE(sum(amount_cents), 0) FROM public.transactions WHERE kind = 'sale' AND status = 'paid'),
    (SELECT count(*) FROM public.bot_start_events),
    (SELECT count(*) FROM public.gateways WHERE provider = 'nxgate' AND status = 'active');
$$;
REVOKE ALL ON FUNCTION public.admin_panel_stats() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.admin_panel_stats() TO service_role;
