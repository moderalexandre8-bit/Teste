-- Detailed funnel analytics and selectable Telegram sales-message layouts.
ALTER TABLE public.bots
  ADD COLUMN IF NOT EXISTS offer_template text NOT NULL DEFAULT 'button_reveal';

ALTER TABLE public.bots DROP CONSTRAINT IF EXISTS bots_offer_template_check;
ALTER TABLE public.bots ADD CONSTRAINT bots_offer_template_check CHECK (
  offer_template IN ('button_reveal', 'classic', 'catalog_grid', 'featured', 'compact')
);

CREATE TABLE IF NOT EXISTS public.bot_start_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL,
  bot_id uuid NOT NULL REFERENCES public.bots(id) ON DELETE CASCADE,
  tg_user_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS bot_start_events_owner_created_idx
  ON public.bot_start_events (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bot_start_events_bot_created_idx
  ON public.bot_start_events (bot_id, created_at DESC);
ALTER TABLE public.bot_start_events ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.bot_start_events TO authenticated;
GRANT ALL ON public.bot_start_events TO service_role;
DROP POLICY IF EXISTS "own bot start events read" ON public.bot_start_events;
CREATE POLICY "own bot start events read" ON public.bot_start_events
  FOR SELECT TO authenticated USING (owner_id = auth.uid());
