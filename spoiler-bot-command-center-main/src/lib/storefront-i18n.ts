const messages: Record<StoreLocale, Record<StoreMessageKey, string>> = {
  "pt-BR": pt,
  en,
  es,
};

export function storeText(locale: StoreLocale, key: StoreMessageKey) {
  return messages[locale][key];
}

export function isStoreLocale(value: unknown): value is StoreLocale {
  return value === "pt-BR" || value === "en" || value === "es";
}

export function storeIntlLocale(locale: StoreLocale) {
  return locale === "pt-BR" ? "pt-BR" : locale === "es" ? "es-ES" : "en-US";
}
