export type TelegramMessageKey = keyof (typeof messages)["pt"];

export function telegramLocale(languageCode?: string | null): TelegramLocale {
  const language = languageCode?.toLowerCase().split(/[-_]/)[0];
  return language === "es" || language === "en" ? language : "pt";
}

export function telegramText(locale: TelegramLocale, key: TelegramMessageKey): string {
  return messages[locale][key];
}

export function localizedTelegramPlanName(
  plan: { name: string; name_en?: string | null; name_es?: string | null },
  locale: TelegramLocale,
): string {
  if (locale === "es" && plan.name_es?.trim()) return plan.name_es;
  if (locale === "en" && plan.name_en?.trim()) return plan.name_en;
  return plan.name;
}
